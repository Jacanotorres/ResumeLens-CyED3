"""Formal definitions and transition diagrams of the profile automata (Stage 3).

The output is Markdown with Mermaid diagrams, which GitHub renders directly.
Regenerate the documentation file after changing a profile:

    python -m resumelens.diagrams
"""

from __future__ import annotations

import sys
from pathlib import Path

from resumelens.classification import build_automaton, build_epsilon_nfa
from resumelens.profiles import PROFILES, Profile

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "diagrams" / "profile-automata.md"


def _tokens(tokens: frozenset[str]) -> str:
    return ", ".join(sorted(tokens))


def to_mermaid(profile: Profile) -> str:
    """Transition diagram of the profile's ε-NFA as a Mermaid flowchart.

    Edges of the same category are grouped in a single labeled arrow; the
    label lists every token a ∈ Cᵢ that fires the transition.
    """
    final = len(profile.categories)
    lines = ["flowchart LR", '    start[" "] --> q0']
    for state in range(final + 1):
        shape = f"q{state}(((q{state})))" if state == final else f"q{state}((q{state}))"
        lines.append(f"    {shape}")
    for state, category in enumerate(profile.categories, start=1):
        label = _tokens(category.tokens)
        lines.append(f'    q{state - 1} -->|"{label}"| q{state}')
        lines.append(f'    q{state} -->|"{label}"| q{state}')
        if not category.required:
            lines.append(f'    q{state - 1} -.->|"ε"| q{state}')
    lines.append("    style start fill:none,stroke:none")
    return "\n".join(lines)


def formal_definition(profile: Profile) -> str:
    """Markdown section with the 5-tuple M = (Q, Σ, δ, q0, F) and the diagram."""
    nfa = build_epsilon_nfa(profile)
    dfa = build_automaton(profile)
    final = len(profile.categories)
    states = ", ".join(f"q{i}" for i in range(final + 1))
    optional = [c.name for c in profile.categories if not c.required]

    rows = []
    for state, category in enumerate(profile.categories, start=1):
        kind = "required" if category.required else "optional"
        transitions = f"δ(q{state - 1}, a) = {{q{state}}}, δ(q{state}, a) = {{q{state}}}"
        if not category.required:
            transitions += f", δ(q{state - 1}, ε) = {{q{state}}}"
        rows.append(
            f"| C{state} | {category.name} ({kind}) | {_tokens(category.tokens)} | {transitions} |"
        )

    pattern = " ".join(
        f"C{i}{'⁺' if c.required else '*'}" for i, c in enumerate(profile.categories, start=1)
    )

    return "\n".join(
        [
            f"## {profile.title}",
            "",
            f"Pattern: `{pattern}`",
            "",
            f"- **Q** = {{{states}}} ({len(nfa.states)} states)",
            f"- **Σ** = {{{_tokens(profile.alphabet)}}} ({len(profile.alphabet)} symbols)",
            "- **q0** = q0",
            f"- **F** = {{q{final}}}",
            f"- **Type:** ε-NFA (ε-transitions skip: {', '.join(optional)})",
            f"- **Equivalent minimal DFA:** {len(dfa.states)} states, "
            "missing transitions go to an implicit dead state",
            "",
            "**δ** (for every a in the category):",
            "",
            "| Category | Name | Tokens a ∈ Cᵢ | Transitions |",
            "|----------|------|---------------|-------------|",
            *rows,
            "",
            "```mermaid",
            to_mermaid(profile),
            "```",
        ]
    )


def render_document() -> str:
    sections = [formal_definition(profile) for profile in PROFILES]
    header = (
        "# Profile automata\n\n"
        "_Generated by `python -m resumelens.diagrams` from `resumelens/profiles.py`; "
        "do not edit by hand._\n\n"
        "Solid arrows read a token; a self-loop accepts more tokens of the same "
        "category; dashed arrows are ε-transitions that skip an optional category. "
        "The double circle is the accepting state."
    )
    return "\n\n".join([header, *sections]) + "\n"


def main() -> int:
    OUTPUT.write_text(render_document(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
