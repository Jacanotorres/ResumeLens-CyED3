"""Results of the full pipeline over the sample résumés.

Runs every résumé in ``data/resumes`` through the four stages and writes:

- ``docs/06-results.md``: what each stage produced and why each profile was
  accepted or rejected;
- ``docs/examples/<résumé>.rl`` and ``.html``: the validated candidate profile
  and its visualization.

Regenerate after changing the pipeline or the samples:

    python -m resumelens.results
"""

from __future__ import annotations

import sys
from pathlib import Path

from resumelens.dsl.builder import to_dsl
from resumelens.dsl.render import render_html
from resumelens.dsl.validator import validate
from resumelens.normalization import normalize
from resumelens.pipeline import ScreeningResult, screen
from resumelens.profiles import PROFILES, Profile, get_profile

ROOT = Path(__file__).resolve().parent.parent
RESUMES = ROOT / "data" / "resumes"
OUTPUT = ROOT / "docs" / "06-results.md"
EXAMPLES = ROOT / "docs" / "examples"


def missing_required(profile: Profile, tokens: list[str]) -> list[str]:
    """Names of the required categories of ``profile`` with no token in ``tokens``."""
    present = set(tokens)
    return [
        category.name
        for category in profile.categories
        if category.required and not (category.tokens & present)
    ]


def _verdict(accepted: bool) -> str:
    return "✅ ACCEPTED" if accepted else "❌ REJECTED"


def _resume_section(path: Path, result: ScreeningResult, dsl_text: str) -> str:
    extraction = result.extraction
    raw_skills = extraction.raw_skills()

    transformations = [
        f"| `{raw}` | `{normalize(raw) or '—'}` |" for raw in raw_skills
    ]

    profile_rows = []
    for match in result.matches:
        profile = get_profile(match.profile_key)
        reason = (
            "All required categories present"
            if match.accepted
            else "Missing: " + ", ".join(missing_required(profile, match.sequence))
        )
        sequence = ", ".join(match.sequence) or "—"
        profile_rows.append(
            f"| {profile.title} | `{sequence}` | {_verdict(match.accepted)} | {reason} |"
        )

    experience = "; ".join(f"{e.years} years — {e.description}" for e in extraction.experience)

    return "\n".join(
        [
            f"## {extraction.name or path.stem}",
            "",
            f"Input: [`data/resumes/{path.name}`](../data/resumes/{path.name})",
            "",
            "**Stage 1 — Extraction (regular expressions)**",
            "",
            f"- Name: {extraction.name or '—'}",
            f"- Experience: {experience or '—'}",
            f"- Raw skills: {', '.join(f'`{s}`' for s in raw_skills) or '—'}",
            "",
            "**Stage 2 — Normalization (finite-state transducer)**",
            "",
            "| Raw string | Canonical token |",
            "|------------|-----------------|",
            *transformations,
            "",
            "**Stages 2b and 3 — Sorting and recognition (finite automata)**",
            "",
            "| Profile | Sequence fed to the automaton | Verdict | Reason |",
            "|---------|-------------------------------|---------|--------|",
            *profile_rows,
            "",
            "**Stage 4 — Candidate profile (validated with textX)**",
            "",
            "```",
            dsl_text.rstrip(),
            "```",
            "",
            f"Visualization: [`examples/{path.stem}.html`](examples/{path.stem}.html)",
        ]
    )


def build() -> tuple[str, dict[str, str]]:
    """Return the Markdown document and the example files ``{name: content}``."""
    paths = sorted(RESUMES.glob("*.txt"))
    sections = []
    examples: dict[str, str] = {}
    summary = []

    for path in paths:
        result = screen(path.read_text(encoding="utf-8"))
        dsl_text = to_dsl(result)
        model = validate(dsl_text)
        examples[f"{path.stem}.rl"] = dsl_text
        examples[f"{path.stem}.html"] = render_html(model)
        sections.append(_resume_section(path, result, dsl_text))
        verdicts = " | ".join("✅" if m.accepted else "❌" for m in result.matches)
        summary.append(f"| {result.extraction.name or path.stem} | {verdicts} |")

    header_profiles = " | ".join(p.title for p in PROFILES)
    document = "\n\n".join(
        [
            "# 6. Results",
            "_Generated by `python -m resumelens.results` from the résumés in "
            "`data/resumes/`; do not edit by hand._",
            "## Summary",
            "\n".join(
                [
                    f"| Résumé | {header_profiles} |",
                    "|--------|" + "---|" * len(PROFILES),
                    *summary,
                ]
            ),
            "## Interpretation",
            "- **The four reference samples are accepted by the profile they were "
            "written for.** The transducer maps different spellings (`JS`, "
            "`React.js`, `Postgres`, `Apache Spark`) to a single canonical token, "
            "so the automata only see canonical symbols.\n"
            "- **Near miss.** Sam Rivera covers the frontend categories of Full "
            "Stack Developer but has no backend or database, so the sequence stops "
            "in an intermediate state and is rejected by every profile.\n"
            "- **More than one profile.** Jordan Lee covers every required category "
            "of DevOps Engineer and of Data Engineer, so both automata accept. The "
            "profiles are evaluated independently; ResumeLens does not pick one.\n"
            "- **A rejection always means a missing required category.** Before "
            "recognition, the tokens are projected onto the profile alphabet and "
            "sorted in its canonical order, so tokens out of order or outside Σ "
            "never reach the automaton. The only way left to fail is a required "
            "category Cᵢ⁺ with no token, which is what the *Reason* column reports.\n"
            "- **Shared skills do not imply a shared profile.** PYTHON, SQL and GIT "
            "appear in several profiles, but a résumé must cover every required "
            "category of a profile to be accepted. For example, the Data Engineer "
            "sample has PYTHON, POSTGRESQL and GIT, but it is rejected as Machine "
            "Learning Engineer because it has no data-processing or ML library.\n"
            "- **Acceptance is not a ranking.** An accepted verdict only states that "
            "the explicitly written qualifications match the formal pattern; it says "
            "nothing about experience level or candidate quality.",
            *sections,
        ]
    )
    return document + "\n", examples


def main() -> int:
    document, examples = build()
    OUTPUT.write_text(document, encoding="utf-8")
    EXAMPLES.mkdir(exist_ok=True)
    for name, content in examples.items():
        (EXAMPLES / name).write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT} and {len(examples)} files in {EXAMPLES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
